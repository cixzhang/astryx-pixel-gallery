import { createRequire } from 'node:module';
const require = createRequire('/home/hatch/workspace/wasm-flame/package.json');
const { chromium } = require('playwright-core');
const EXE = '/home/hatch/.cache/ms-playwright/chromium_headless_shell-1243/chrome-headless-shell-linux64/chrome-headless-shell';
const OUT = new URL('.', import.meta.url).pathname;
const b = await chromium.launch({ executablePath: EXE, args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1280, height: 1150 }, deviceScaleFactor: 1 });
p.on('pageerror', e => console.log('pageerror:', e.message.slice(0, 160)));
await p.goto('http://127.0.0.1:8332/', { waitUntil: 'networkidle' });
await p.waitForTimeout(1500);
await p.screenshot({ path: OUT + 'gal-garden.png', fullPage: true });
console.log('shot garden');
await p.locator('text=Game Boy').first().click();
await p.waitForTimeout(700);
await p.screenshot({ path: OUT + 'gal-gameboy.png', fullPage: true });
console.log('shot gameboy light');
await p.getByRole('button', { name: 'Dark' }).click();
await p.waitForTimeout(700);
await p.screenshot({ path: OUT + 'gal-gameboy-dark.png', fullPage: true });
console.log('shot gameboy dark');
await p.locator('text=PICO-8').first().click();
await p.waitForTimeout(700);
await p.screenshot({ path: OUT + 'gal-pico8-dark.png', fullPage: true });
console.log('shot pico8 dark');
await b.close();
