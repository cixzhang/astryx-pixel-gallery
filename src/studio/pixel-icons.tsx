/**
 * Pixel icons + indicators for the pixel theme.
 *
 * Icons are drawn the way grid fonts are drawn: as pixel matrices on a
 * fixed 12×12 grid, rendered as SVG <rect>s with crispEdges and
 * currentColor fill. They are data, not paths — the same discipline as
 * Silkscreen's glyph grid — so they stay honest at any size the grid
 * divides. (Reference set for this approach: pixelarticons, drawn on a
 * 24×24 grid; ours are hand-drawn matrices because the theme needs
 * Astryx's 27 semantic names, not a general library.)
 *
 * Indicators replace Astryx's selection visuals (theme `indicators`):
 * a stepped pixel ring for radio, a stepped box + pixel check for
 * checkbox, and a bare pixel check for chosen menu rows.
 */
import React from 'react';
import type { ReactElement, ReactNode } from 'react';

// The astryx theme-build loader transpiles JSX with the classic runtime
// (needs React in scope) while Vite uses the automatic runtime.
void React;

// ── matrix renderer ─────────────────────────────────────────────────
function glyph(rows: string[], cellFill = 'currentColor'): ReactElement {
  const rects: ReactElement[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') {
        rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={cellFill} />);
      }
    }
  });
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={`0 0 ${rows[0].length} ${rows.length}`}
      width="1em"
      height="1em"
      aria-hidden
      shapeRendering="crispEdges"
    >
      {rects}
    </svg>
  );
}

