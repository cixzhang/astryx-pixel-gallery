// ── indicators ──────────────────────────────────────────────────────
const isRenderable = (n: ReactNode): boolean => n != null && typeof n !== 'boolean';

type IndicatorProps = {
  state: string;
  size?: 'sm' | 'md';
  isDisabled?: boolean;
  children?: ReactNode;
};

function IndicatorSvg({
  rows,
  px,
  children,
}: {
  rows: ReactElement;
  px: number;
  children?: ReactNode;
}) {
  if (isRenderable(children)) {
    return (
      <span aria-hidden style={{ display: 'inline-flex', width: px, height: px }}>
        {children}
      </span>
    );
  }
  return (
    <span aria-hidden style={{ display: 'inline-flex', width: px, height: px }}>
      {rows}
    </span>
  );
}

