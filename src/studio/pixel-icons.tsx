function layered(layers: Array<{ rows: string[]; fill: string }>): ReactElement {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 12 12"
      width="100%"
      height="100%"
      aria-hidden
      shapeRendering="crispEdges"
    >
      {layers.map((layer, i) => (
        <g key={i} fill={layer.fill}>
          {layer.rows.flatMap((row, y) =>
            [...row].map((c, x) =>
              c === '#' ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} /> : null,
            ),
          )}
        </g>
      ))}
    </svg>
  );
}

export function PixelRadioIndicator({ state, size = 'md', isDisabled, children }: IndicatorProps) {
  const px = size === 'sm' ? 20 : 24;
  const ringFill = isDisabled ? 'var(--color-text-disabled)' : 'var(--color-border-emphasized)';
  const dotFill = isDisabled ? 'var(--color-text-disabled)' : 'var(--color-accent)';
  const svg = layered(
    state === 'checked'
      ? [
          { rows: RING, fill: ringFill },
          { rows: DOT, fill: dotFill },
        ]
      : [{ rows: RING, fill: ringFill }],
  );
  return <IndicatorSvg rows={svg} px={px} children={children} />;
}

export function PixelCheckboxIndicator({ state, size = 'md', isDisabled, children }: IndicatorProps) {
  const px = size === 'sm' ? 20 : 24;
  const edge = isDisabled ? 'var(--color-text-disabled)' : 'var(--color-border-emphasized)';
  const mark = isDisabled ? 'var(--color-text-disabled)' : 'var(--color-accent)';
  const layers =
    state === 'checked'
      ? [
          { rows: BOX, fill: edge },
          { rows: BOX_CHECK, fill: mark },
        ]
      : state === 'indeterminate'
        ? [
            { rows: BOX, fill: edge },
            { rows: BOX_BAR, fill: mark },
          ]
        : [{ rows: BOX, fill: edge }];
  return <IndicatorSvg rows={layered(layers)} px={px} children={children} />;
}

export function PixelCheckIndicator({ state, size = 'md', children }: IndicatorProps) {
  const px = size === 'sm' ? 20 : 24;
  const svg =
    state === 'checked' ? (
      layered([{ rows: M.check, fill: 'var(--color-accent)' }])
    ) : (
      <svg viewBox="0 0 12 12" width="100%" height="100%" aria-hidden />
    );
  return <IndicatorSvg rows={svg} px={px} children={children} />;
}
